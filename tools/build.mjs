// Build: plugin/solid-sound-custom/includes/custom.php  ->  plugin/solid-sound-custom/build/
//   build/custom.php      same PHP, big static <style>/<script> blocks replaced by ss_asset('name')
//   build/assets/*.css|js minified, content-hashed (cache forever)
//   build/assets.php      name => file map used by ss_asset()
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync, rmSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { transformSync } from 'esbuild';
const root = new URL('../plugin/solid-sound-custom/', import.meta.url).pathname;
const raw = '/tmp/ss-build-raw';
rmSync(root + 'build', { recursive: true, force: true }); rmSync(raw, { recursive: true, force: true });
mkdirSync(root + 'build/assets', { recursive: true });
execFileSync('php', [new URL('extract-assets.php', import.meta.url).pathname, root + 'src/custom.php', root + 'build/custom.php', raw], { stdio: 'inherit' });
execFileSync('php', ['-l', root + 'build/custom.php'], { stdio: 'inherit' });
const manifest = JSON.parse(readFileSync(raw + '/manifest.json', 'utf8'));
const map = {}; let before = 0, after = 0;
// standalone source files that become assets as they are
for (const [name, file] of [['ss-global', 'src/ss-global.js']]) {
  manifest[name] = { type: 'js', id: null, standalone: root + file };
}
for (const [name, m] of Object.entries(manifest)) {
  const src = readFileSync(m.standalone || `${raw}/${name}.${m.type}`, 'utf8');
  const out = transformSync(src, { loader: m.type, minify: true, legalComments: 'none', target: m.type === 'js' ? 'es2017' : undefined }).code;
  const hash = createHash('sha256').update(out).digest('hex').slice(0, 10);
  const file = `${name}.${hash}.${m.type}`;
  writeFileSync(root + 'build/assets/' + file, out);
  map[name] = { f: file, t: m.type, id: m.id };
  before += src.length; after += out.length;
}
const php = '<?php\n// Generated by tools/build.mjs. Do not edit.\nreturn ' +
  JSON.stringify(map, null, 1).replace(/\{/g, 'array(').replace(/\}/g, ')').replace(/":/g, '" =>').replace(/"/g, "'").replace(/\[/g, 'array(').replace(/\]/g, ')') + ';\n';
writeFileSync(root + 'build/assets.php', php);
execFileSync('php', ['-l', root + 'build/assets.php'], { stdio: 'inherit' });
console.log(`assets: ${Object.keys(map).length}, ${Math.round(before / 1024)} KB -> ${Math.round(after / 1024)} KB minified`);
