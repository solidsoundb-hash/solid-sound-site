// Build: plugin/solid-sound-custom/includes/custom.php  ->  plugin/solid-sound-custom/build/
//   build/custom.php      same PHP, big static <style>/<script> blocks replaced by ss_asset('name')
//   build/assets/*.css|js minified, content-hashed (cache forever)
//   build/assets.php      name => file map used by ss_asset()
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync, rmSync, readdirSync, cpSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { transformSync } from 'esbuild';
const root = new URL('../plugin/solid-sound-custom/', import.meta.url).pathname;
const raw = '/tmp/ss-build-raw';
rmSync(root + 'build', { recursive: true, force: true }); rmSync(raw, { recursive: true, force: true });
mkdirSync(root + 'build/assets', { recursive: true });
cpSync(root + 'src/media', root + 'build/media', { recursive: true }); /* static media (example audio) */
execFileSync('php', [new URL('extract-assets.php', import.meta.url).pathname, root + 'src/custom.php', root + 'build/custom.php', raw], { stdio: 'inherit' });
execFileSync('php', ['-l', root + 'build/custom.php'], { stdio: 'inherit' });
const manifest = JSON.parse(readFileSync(raw + '/manifest.json', 'utf8'));
const map = {}; let before = 0, after = 0;
// Home app: apply the text patches ONCE (src/home/patches.js) and bundle template + data + runtime
{
  const { createRequire } = await import('node:module');
  const req = createRequire(import.meta.url);
  const H = root + 'src/home/';
  const win = { SS_TRI: (readFileSync(H + 'home.js', 'utf8').match(/window\.SS_TRI='([^']+)'/) || [])[1] };
  const a = [readFileSync(H + 'app.template.html', 'utf8'), readFileSync(H + 'runtime.js', 'utf8')];
  req(H + 'patches.js')(a, win);
  const data = {}; for (const k of Object.keys(win)) if (k !== 'SS_TRI') data[k] = win[k];
  // template body goes to the runtime directly (window.__ssTpl): never parsed into the live page,
  // so no "{{...}}" SVG errors; only an empty <x-dc> and the inert logic script are inserted.
  let rt = a[1];
  const hook = 'return{template:n.innerHTML,';
  if (rt.split(hook).length !== 2) throw new Error('home: runtime template hook not found');
  rt = rt.replace(hook, 'return{template:window.__ssTpl||n.innerHTML,');
  const js = (x) => JSON.stringify(x).replace(/<\/(script)/gi, '<\\/$1');
  const write = (name, tpl, extra) => {
    const m = tpl.match(/^\s*<x-dc>([\s\S]*)<\/x-dc>\s*([\s\S]*)$/);
    if (!m) throw new Error('home: template root <x-dc> not found');
    writeFileSync(raw + '/' + name + '.js',
      ('/* generated by tools/build.mjs from src/home (template + patches + runtime) */\n' +
      'Object.assign(window,' + JSON.stringify(Object.assign({}, data, extra || {})) + ');\n' +
      // __resources set: the runtime must not download the whole page again just to re-read the template
      'window.__resources=window.__resources||{};window.__ssTpl=' + js(m[1]) + ';\n' +
      '(function(){var b=document.getElementById("ss-app");if(b)b.innerHTML="<x-dc></x-dc>"+' + js(m[2]) + ';})();\n' + rt)
      // ASCII-only file: correct even if a server sends it without a charset
      .replace(/[\u0080-\uffff]/g, c => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0')));
    manifest[name] = { type: 'js', id: null, standalone: [raw + '/' + name + '.js'], noMinify: true };
  };
  write('home-app', a[0]);
  // other languages (owner 17.11: new home on every language): texts from src/home/i18n/<lang>.json,
  // links to the home and the Wiki go to that language; pages without a translation stay English.
  const I18N = await import('./home-i18n.mjs');
  const WIKI = { ua: 'wiki-ua', de: 'wiki-de', fr: 'wiki-fr', es: 'wiki-es', it: 'wiki-it', pt: 'wiki-pt' };
  const common = existsSync(H + 'i18n/_numbers.json') ? JSON.parse(readFileSync(H + 'i18n/_numbers.json', 'utf8')) : {};
  for (const f of existsSync(H + 'i18n') ? readdirSync(H + 'i18n') : []) {
    const L = (f.match(/^([a-z]{2})\.json$/) || [])[1]; if (!L) continue;
    const dict = Object.assign({}, common[L] || {}, JSON.parse(readFileSync(H + 'i18n/' + f, 'utf8')));
    let t = I18N.apply(a[0], dict);
    t = t.replace(/(https:\/\/solid-sound\.net)?\/en\/(wiki\/)?(?=['"])/g, (x, host, w) => (host || '') + '/' + L + '/' + (w ? WIKI[L] + '/' : ''));
    const back = {}; for (const [k, v] of Object.entries(dict)) if (k.length < 40 && !/[&;]/.test(k)) back[v] = k;
    const short = {}; for (const [k, v] of Object.entries(dict)) if (k.length < 120) short[k] = v;
    const trD = (o) => typeof o === 'string' ? (dict[o] || o) : Array.isArray(o) ? o.map(trD) : o && typeof o === 'object' ? Object.fromEntries(Object.entries(o).map(([k, v]) => [k, trD(v)])) : o;
    write('home-app-' + L, t, Object.assign(trD(data), { SS_EN: back, SS_TR: short, SS_LANG: L }));
  }
}
// standalone source files that become assets as they are
for (const [name, type, files, noMinify] of [
  ['ss-global', 'js', ['src/ss-global.js']],
  ['ss-account-css', 'css', ['src/account/dashboard.css', 'src/account/shell.css']],
  ['ss-account-js', 'js', ['src/account/dashboard.js']],
  ['ss-cab', 'js', ['src/account/cab.js']],
  ['home-css', 'css', ['src/home/home.css', 'src/home/parts/assistant.css']],
  ['theme-player-css', 'css', ['src/theme/player.css']],
  ['theme-player-js', 'js', ['src/theme/player.js']],
  ['home-js', 'js', ['src/home/home.js']],
  ['home-ai', 'js', ['src/home/ai-search.js']],
  ['react', 'js', ['src/home/vendor/react.production.min.js'], true],
  ['react-dom', 'js', ['src/home/vendor/react-dom.production.min.js'], true],
]) {
  manifest[name] = { type, id: null, standalone: files.map(f => root + f), noMinify: !!noMinify };
}
// PHP modules are copied as they are
mkdirSync(root + 'build/modules', { recursive: true });
for (const f of readdirSync(root + 'src/modules')) {
  writeFileSync(root + 'build/modules/' + f, readFileSync(root + 'src/modules/' + f));
  execFileSync('php', ['-l', root + 'build/modules/' + f], { stdio: 'inherit' });
}
for (const [name, m] of Object.entries(manifest)) {
  const src = m.standalone ? m.standalone.map(f => readFileSync(f, 'utf8')).join('\n') : readFileSync(`${raw}/${name}.${m.type}`, 'utf8');
  const out = m.noMinify ? src : transformSync(src, { loader: m.type, minify: true, legalComments: 'none', target: m.type === 'js' ? 'es2017' : undefined }).code;
  const hash = createHash('sha256').update(out).digest('hex').slice(0, 10);
  const file = `${name}.${hash}.${m.type}`;
  writeFileSync(root + 'build/assets/' + file, out);
  map[name] = { f: file, t: m.type, id: m.id };
  before += src.length; after += out.length;
}
const php = '<?php\n// Generated by tools/build.mjs. Do not edit.\nreturn ' +
  JSON.stringify(map, null, 1).replace(/\{/g, 'array(').replace(/\}/g, ')').replace(/":/g, '" =>').replace(/"/g, "'").replace(/\[/g, 'array(').replace(/\]/g, ')') + ';\n';
writeFileSync(root + 'build/assets.php', php);
execFileSync('php', ['-l', root + 'build/assets.php'], { stdio: 'inherit' });
console.log(`assets: ${Object.keys(map).length}, ${Math.round(before / 1024)} KB -> ${Math.round(after / 1024)} KB minified`);
